#!/usr/bin/env bash
# Deploy CAML onto a local storage drive (e.g. an external disk) and keep
# everything it writes on that drive: framework venvs, uv's cache and Python
# downloads, OpenML datasets, results, temp files, and every tool's ~/.cache
# (HF/torch weights, matplotlib, ...). Nothing new lands on the system disk.
# The local-machine counterpart of scripts/sync_vps.sh, added 2026-10-21 when
# Ali moved the paper runs off rented VPSes onto a laptop whose system disk
# had ~13GB free.
#
# Usage (from inside this repo):
#   CAML_STORAGE=/mnt/MIRC/CAML-STORAGE scripts/sync_local.sh          # HEAD
#   INCLUDE_WORKTREE=1 CAML_STORAGE=... scripts/sync_local.sh           # working tree
#   FORCE=1 ...           # sync even while a caml run/sweep from it is running
#   ALLOW_SYSTEM_DISK=1   # allow CAML_STORAGE on the same filesystem as /
#
# The first run creates the layout; later runs only replace source files.
# Framework venvs, install markers, output/ and input/ are not in the archive,
# so installs and results survive (same semantics as sync_vps.sh, including:
# files deleted locally are not deleted from the workspace).
#
# Layout:
#   $CAML_STORAGE/
#     caml-env.sh         source before any caml command (regenerated each sync)
#     secrets.env         optional, yours: e.g. `export TABPFN_TOKEN=...`
#     workspace/CAML/     deployed code + frameworks/*/venv, .venv, output/
#     home/               HOME for caml and every framework subprocess
#     cache/ config/ data/ state/   XDG_* dirs (uv cache, openml, HF, ...)
#     python/             uv-managed Python interpreters
#     tmp/                TMPDIR
#     logs/               scripts/run_local_detached.sh logs and pid files
set -euo pipefail

STORAGE="${CAML_STORAGE:-}"
if [[ -z "$STORAGE" ]]; then
  echo "usage: CAML_STORAGE=<dir on the storage drive> $0" >&2
  exit 2
fi
INCLUDE_WORKTREE="${INCLUDE_WORKTREE:-0}"
FORCE="${FORCE:-0}"
ALLOW_SYSTEM_DISK="${ALLOW_SYSTEM_DISK:-0}"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || { echo "must be run from inside the CAML git checkout." >&2; exit 1; }

[[ -d "$STORAGE" ]] || { echo "CAML_STORAGE=$STORAGE does not exist (is the drive mounted?)." >&2; exit 1; }
STORAGE="$(cd "$STORAGE" && pwd -P)"
if [[ "$(stat -c %d "$STORAGE")" == "$(stat -c %d /)" && "$ALLOW_SYSTEM_DISK" != "1" ]]; then
  echo "Refusing: $STORAGE is on the same filesystem as / (the point is to keep the system disk clean). Set ALLOW_SYSTEM_DISK=1 to override." >&2
  exit 1
fi

WS="$STORAGE/workspace/CAML"

if [[ "$FORCE" != "1" ]]; then
  # Same guard as sync_vps.sh: swapping code under a running sweep would
  # silently mix revisions between jobs. Bracket trick: '[c]aml' doesn't
  # match this grep's own command line.
  running="$(ps -eo pid,args | grep -E '[c]aml (run|sweep|install)' | grep -F "$WS" || true)"
  if [[ -n "$running" ]]; then
    echo "Refusing to sync: a CAML job is running from $WS:" >&2
    echo "$running" >&2
    echo "Wait for it to finish (or stop it), or re-run with FORCE=1." >&2
    exit 1
  fi
fi

mkdir -p "$STORAGE"/{workspace,home,cache,config,data,state,python,tmp,logs}

cat > "$STORAGE/caml-env.sh" <<EOF
# Generated by scripts/sync_local.sh -- regenerated on every sync, don't edit.
# Put your own exports (e.g. TABPFN_TOKEN) in $STORAGE/secrets.env instead.
export CAML_STORAGE="$STORAGE"
export CAML_ROOT="$WS"
export HOME="$STORAGE/home"
export XDG_CACHE_HOME="$STORAGE/cache"
export XDG_CONFIG_HOME="$STORAGE/config"
export XDG_DATA_HOME="$STORAGE/data"
export XDG_STATE_HOME="$STORAGE/state"
export UV_CACHE_DIR="$STORAGE/cache/uv"
export UV_PYTHON_INSTALL_DIR="$STORAGE/python"
export UV_PYTHON_BIN_DIR="$STORAGE/python/bin"
# Only interpreters uv installed under python/ -- never a Python that happens
# to be on the system disk -- so the drive is self-contained and portable.
export UV_PYTHON_PREFERENCE=only-managed
export TMPDIR="$STORAGE/tmp" TMP="$STORAGE/tmp" TEMP="$STORAGE/tmp"
export PATH="$WS/.venv/bin:\$PATH"
if [ -f "$STORAGE/secrets.env" ]; then . "$STORAGE/secrets.env"; fi
EOF

ARCHIVE="$(mktemp --suffix=.tar.gz)"
trap 'rm -f "$ARCHIVE"' EXIT
source "$REPO_ROOT/scripts/lib_package.sh"
caml_package_archive "$ARCHIVE" "$INCLUDE_WORKTREE"
echo "==> packaged $([[ "$INCLUDE_WORKTREE" == 1 ]] && echo 'working tree' || echo 'HEAD') at $(git rev-parse --short HEAD)"

# The drive is often NTFS/exFAT, where ownership and modes can't be set.
tar xzf "$ARCHIVE" -C "$STORAGE/workspace" --no-same-owner --no-same-permissions

# shellcheck source=/dev/null
source "$STORAGE/caml-env.sh"
(cd "$WS" && uv sync -q)
echo "==> synced to $WS"
cat "$WS/REVISION"
echo "==> before any caml command:  source $STORAGE/caml-env.sh"
